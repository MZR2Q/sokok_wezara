function svgIcon(name, size = 20) {
  const p = ICON[name] || "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${p}</svg>`;
}
function icon(name, size = 20, cls = "") {
  return `<span class="i-svg ${cls}">${svgIcon(name, size)}</span>`;
}

/* استبدال الأيقونات المعلَّمة في HTML الثابت مع الحفاظ على أصناف العنصر:
   <span class="ic" data-icon="building" data-size="20"></span> */
function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((n) => {
    const size = parseInt(n.getAttribute("data-size")) || 20;
    n.innerHTML = svgIcon(n.getAttribute("data-icon"), size);
    n.classList.add("i-svg");
    n.removeAttribute("data-icon");
  });
}
document.addEventListener("DOMContentLoaded", () => hydrateIcons());
